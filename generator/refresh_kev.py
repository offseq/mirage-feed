"""Rebuild kev.txt from the CISA Known Exploited Vulnerabilities catalog.

Run by hand (`python -m generator.refresh_kev`), review the diff, commit. Never runs in CI.
"""

import json
import urllib.request
from datetime import UTC, datetime

from .common import CVE
from .kev import KEV_FILE

SOURCE = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json"


def main() -> None:
    with urllib.request.urlopen(SOURCE, timeout=60) as resp:
        catalog = json.load(resp)
    cves = sorted({v["cveID"] for v in catalog["vulnerabilities"] if CVE.fullmatch(v["cveID"])})
    header = [
        f"# CISA KEV catalog CVE ids. Source: {SOURCE}",
        f"# Retrieved {datetime.now(UTC):%Y-%m-%d} (catalog {catalog['catalogVersion']}). "
        "Generated by generator/refresh_kev.py; do not edit.",
    ]
    KEV_FILE.write_text("\n".join([*header, *cves]) + "\n", encoding="utf-8")
    print(f"{KEV_FILE}: {len(cves)} CVEs")


if __name__ == "__main__":
    main()
